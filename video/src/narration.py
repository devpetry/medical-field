def phonetic(text: str) -> str:
    out = text
    for a, b in _PHONETIC:
        out = out.replace(a, b)
    out = re.sub(r"\bID\b", "ái dí", out)
    # Palavras em caixa alta seriam soletradas.
    for w in ("OFFLINE", "ONLINE", "DUPLICADO", "SINCRONIZADO", "SAMU"):
        out = out.replace(w, w.lower())
    return out


